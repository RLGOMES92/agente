-- Durable outbound outbox. Enqueue content before delivery; retries never regenerate AI responses.
create table if not exists public.message_outbox (
  id bigint generated by default as identity primary key,
  company_id text not null references public.companies(id) on delete cascade,
  destination text not null check (destination ~ '^\\d{8,15}$'),
  body text not null check (length(body) between 1 and 4096),
  idempotency_key text not null unique,
  status text not null default 'pending' check (status in ('pending','processing','sent','failed')),
  attempts integer not null default 0,
  available_at timestamptz not null default now(),
  locked_at timestamptz,
  last_error text,
  provider_message_id text,
  created_at timestamptz not null default now(),
  sent_at timestamptz
);
create index if not exists idx_outbox_claim on public.message_outbox(status,available_at,id);
alter table public.message_outbox enable row level security;
revoke all on public.message_outbox from anon, authenticated;
grant all on public.message_outbox to service_role;
grant usage, select on sequence public.message_outbox_id_seq to service_role;

create or replace function public.claim_message_outbox(p_limit integer default 10)
returns setof public.message_outbox
language sql security definer set search_path=public
as $function$
 with candidates as (
  select id from public.message_outbox
  where available_at <= now() and (
    status='pending' or (status='processing' and locked_at < now()-interval '5 minutes')
  )
  order by id for update skip locked
  limit greatest(1,least(coalesce(p_limit,10),20))
 )
 update public.message_outbox o
 set status='processing', attempts=o.attempts+1, locked_at=now(), last_error=null
 from candidates c where o.id=c.id returning o.*;
$function$;
revoke all on function public.claim_message_outbox(integer) from public, anon, authenticated;
grant execute on function public.claim_message_outbox(integer) to service_role;
