create extension if not exists pgcrypto;

create table if not exists public.companies (
  id text primary key check (id ~ '^[a-z0-9][a-z0-9_-]{0,39}$'),
  phone_number_id text unique,
  token_env text not null,
  team_number text not null default '',
  variables jsonb not null default '{}'::jsonb,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  email text not null unique,
  password_hash text not null,
  password_salt text not null,
  role text not null check (role in ('platform_admin','company_admin','operator','viewer')),
  company_id text references public.companies(id) on delete cascade,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  last_login_at timestamptz,
  check ((role='platform_admin' and company_id is null) or (role<>'platform_admin' and company_id is not null))
);

create table if not exists public.user_sessions (
  token_hash text primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);
create index if not exists user_sessions_expiry_idx on public.user_sessions(expires_at);

create table if not exists public.conversations (
  company_id text not null references public.companies(id) on delete cascade,
  phone text not null,
  paused boolean not null default false,
  updated_at timestamptz not null default now(),
  primary key(company_id,phone)
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  company_id text not null,
  phone text not null,
  role text not null check (role in ('user','assistant')),
  content text not null,
  created_at timestamptz not null default now(),
  foreign key(company_id,phone) references public.conversations(company_id,phone) on delete cascade
);
create index if not exists messages_thread_idx on public.messages(company_id,phone,id desc);

create table if not exists public.seen_webhook_events (
  id text primary key,
  created_at timestamptz not null default now()
);
create index if not exists seen_webhook_events_created_idx on public.seen_webhook_events(created_at);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  company_id text references public.companies(id) on delete set null,
  actor_user_id bigint references public.users(id) on delete set null,
  action text not null,
  target_type text,
  target_id text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.message_jobs (
  id bigint generated by default as identity primary key,
  company_id text not null references public.companies(id) on delete cascade,
  phone text not null,
  message_id text not null unique,
  payload jsonb not null,
  status text not null default 'pending' check (status in ('pending','processing','completed','failed')),
  attempts integer not null default 0,
  available_at timestamptz not null default now(),
  locked_at timestamptz,
  completed_at timestamptz,
  last_error text,
  created_at timestamptz not null default now()
);
create index if not exists message_jobs_pending_idx on public.message_jobs(status,available_at,id);

alter table public.companies enable row level security;
alter table public.users enable row level security;
alter table public.user_sessions enable row level security;
alter table public.conversations enable row level security;
alter table public.messages enable row level security;
alter table public.seen_webhook_events enable row level security;
alter table public.audit_logs enable row level security;
alter table public.message_jobs enable row level security;

-- Backend-only tables: no client-side policies. Access requires the secret key.
revoke all on public.companies,public.users,public.user_sessions,public.conversations,public.messages,public.seen_webhook_events,public.audit_logs,public.message_jobs from anon,authenticated;
grant all on public.companies,public.users,public.user_sessions,public.conversations,public.messages,public.seen_webhook_events,public.audit_logs,public.message_jobs to service_role;
grant usage,select on all sequences in schema public to service_role;
